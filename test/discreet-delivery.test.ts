import { expect, test } from "bun:test";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Factory } from "../src/app.ts";
import { repoSettings } from "../src/config.ts";
import { cachePath, createWorktree, ensureCache } from "../src/git/repos.ts";
import { sh } from "../src/util/proc.ts";
import { approve, holdout, pass, pipelineSetup, roleOf, spec, triage, waitFor } from "./pipeline-support.ts";

const state = { home: "", repoDir: "", factory: null as Factory | null };
const { start, githubFixture, registerGithub } = pipelineSetup(state);

test.each([true, false])("delivery publishes expected text (discreet: %s)", async (discreet) => {
  const bare = await githubFixture();
  mkdirSync(join(state.home, "cfg"));
  writeFileSync(join(state.home, "cfg", "config.toml"), `[repos."test/repo"]\ndiscreet = ${discreet}`);
  const f = start((s) => {
    switch (roleOf(s)) {
      case "triage":
        return { structured: triage() };
      case "spec":
        return { structured: spec };
      case "holdout":
        return { structured: holdout };
      case "review":
        return { structured: approve };
      case "verify":
        return { structured: pass };
      default:
        return { files: { "farewell.txt": "goodbye\n" }, text: "Added farewell" };
    }
  });
  registerGithub(f, bare);
  const created = await f.createRun({
    repo: "test/repo",
    prompt: "Add farewell",
    title: "Add farewell",
    profile: "standard",
  });
  expect(await waitFor(f, created.id, ["succeeded", "failed", "needs_human"])).toBe("succeeded");
  const run = f.store.getRun(created.id);
  if (!run?.branch || !run.prUrl) throw new Error("missing delivery record");
  expect(f.store.runForPr(run.prUrl)?.id).toBe(run.id);
  const body = readFileSync(join(state.home, "gh-body"), "utf8");
  const calls = readFileSync(join(state.home, "gh-calls"), "utf8");
  const message = (await sh(["git", "log", "-1", "--format=%B", run.branch], { cwd: bare })).stdout.trim();
  expect(body).toContain("## Checks");
  expect(body).toContain("## Code review");
  expect(calls).toContain("--title Add farewell");
  if (discreet) {
    expect(run.branch).toBe("change/add-farewell");
    expect(message).toBe(run.title);
    for (const text of [run.branch, message, calls, body]) {
      expect(text).not.toMatch(/limitless/i);
      expect(text).not.toContain(run.id);
      expect(text).not.toContain(`${f.cfg.uiUrl}/runs/`);
    }
  } else {
    expect(run.branch).toBe(`limitless/${run.id}-add-farewell`);
    expect(message).toBe(`limitless: ${run.title} (round 1)\n\nRun: ${run.id}`);
    expect(body.trim()).toEndWith("🤖 Generated by Limitless");
  }
});

test("branch allocation checks stored, local and remote names and resumes a suffixed branch", async () => {
  const bare = await githubFixture();
  const f = start(() => ({ text: "unused" }));
  await f.scheduler.stop();
  registerGithub(f, bare);
  const repo = f.store.getRepoBySlug("test/repo");
  if (!repo) throw new Error("missing repo");
  f.cfg.repos = { "test/repo": { discreet: true, branchPrefix: "change/" } };
  await ensureCache(f.cfg.paths, repo);
  const allocate = async () => {
    const run = f.store.createRun(repo, { repo: repo.slug, prompt: "Add farewell", title: "Add farewell" });
    const wt = await createWorktree(f.cfg.paths, repo, run.id, run.title, "main", {
      cfg: f.cfg,
      store: f.store,
    });
    return f.store.updateRun(run.id, { branch: wt.branch });
  };
  expect((await allocate()).branch).toBe("change/add-farewell");
  const second = await allocate();
  expect(second.branch).toBe("change/add-farewell-2");
  f.cfg.repos["test/repo"] = { discreet: true, branchPrefix: "feat/" };
  expect(
    (
      await createWorktree(f.cfg.paths, repo, second.id, "Different title", "main", {
        cfg: f.cfg,
        store: f.store,
      })
    ).branch,
  ).toBe(second.branch ?? "");
  expect((await allocate()).branch).toBe("feat/add-farewell");
  f.cfg.repos["test/repo"] = { discreet: true, branchPrefix: "change/" };
  const cache = cachePath(f.cfg.paths, repo);
  await sh(["git", "update-ref", "refs/heads/change/add-farewell-3", "refs/remotes/origin/main"], {
    cwd: cache,
  });
  await sh(["git", "update-ref", "refs/remotes/origin/change/add-farewell-4", "refs/remotes/origin/main"], {
    cwd: cache,
  });
  const recorded = f.store.createRun(repo, { repo: repo.slug, prompt: "recorded" });
  f.store.updateRun(recorded.id, { branch: "change/add-farewell-5" });
  expect((await allocate()).branch).toBe("change/add-farewell-6");
  f.cfg.repos["test/repo"] = { discreet: false, branchPrefix: "feat/" };
  const ordinary = await allocate();
  expect(ordinary.branch).toBe(`limitless/${ordinary.id}-add-farewell`);
  expect(repoSettings(f.cfg, repo.slug).discreet).toBe(false);
});
